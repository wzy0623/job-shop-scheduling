# instance.py
# --------------------------------------------------
# 一个 3 Jobs × 3 Machines 的 Job Shop Scheduling 实例
#
# 数据格式：
# job_id: [
#     (machine_id, processing_time),
#     ...
# ]
# --------------------------------------------------

JOBS = {
    1: [
        (1, 3),   # J1 的第 1 道工序：M1，加工 3 个时间单位
        (2, 2),   # J1 的第 2 道工序：M2，加工 2 个时间单位
        (3, 2),   # J1 的第 3 道工序：M3，加工 2 个时间单位
    ],

    2: [
        (2, 2),   # J2 的第 1 道工序：M2，加工 2 个时间单位
        (3, 1),   # J2 的第 2 道工序：M3，加工 1 个时间单位
        (1, 4),   # J2 的第 3 道工序：M1，加工 4 个时间单位
    ],

    3: [
        (3, 4),   # J3 的第 1 道工序：M3，加工 4 个时间单位
        (1, 3),   # J3 的第 2 道工序：M1，加工 3 个时间单位
        (2, 1),   # J3 的第 3 道工序：M2，加工 1 个时间单位
    ],
}


MACHINES = [1, 2, 3]


# 所有加工时间之和
#
# 即：
#
# J1: 3 + 2 + 2 = 7
# J2: 2 + 1 + 4 = 7
# J3: 4 + 3 + 1 = 8
#
# 总和 = 22
#
# 如果把所有工序完全串行执行，
# 22 已经可以作为一个可行的 Makespan 上界，
# 因此可以作为本模型中的 Big-M。

BIG_M = sum(
    processing_time
    for operations in JOBS.values()
    for _, processing_time in operations
)